"""
analyze_simulation_results.py

Analysis code for:

Governing Agentic AI Under Deep Uncertainty:
Scenario-Based Stress Tests of Institutional Containment

This script reads the combined 784-row topology sweep generated by:

    institutional_containment_stress_test.py

and produces:

1. Design-wide scenario means
2. Topology ~ p marginal means
3. Topology ~ tau marginal means
4. Topology ~ FN marginal means
5. Matched-condition contrasts relative to S0
6. Low-to-high endpoint contrasts
7. Structural checks for the S0-S2 comparison

The analysis is descriptive and simulation-based.
It does not estimate real-world agentic-AI incident frequencies.
"""

from pathlib import Path

import numpy as np
import pandas as pd


# ======================================================================
# PATHS
# ======================================================================

INPUT = Path(
    "./simulation_output/scenario_sweep_784.csv"
)

OUTDIR = Path(
    "./analysis_output"
)

OUTDIR.mkdir(
    parents=True,
    exist_ok=True,
)


# ======================================================================
# EXPERIMENT DEFINITIONS
# ======================================================================

SCENARIO_ORDER = [
    "S0_maximal_connectivity",
    "S1_sparse_sequential",
    "S2_hub_mediated",
    "S3_layered",
]

SCENARIO_LABELS = {
    "S0_maximal_connectivity":
        "S0 Maximal-Connectivity Topology",

    "S1_sparse_sequential":
        "S1 Sparse Sequential Topology",

    "S2_hub_mediated":
        "S2 Hub-Mediated Topology",

    "S3_layered":
        "S3 Layered Topology",
}

OUTCOMES = [
    "systemic_contagion_pct",
    "cross_cell_leakage_pct",
    "strategic_velocity_pct",
    "propagated_exposure",
    "compromised_execution_persistence",
]


# ======================================================================
# HELPERS
# ======================================================================

def close_mask(series, value):
    return np.isclose(
        series.astype(float),
        float(value),
    )


def endpoint_contrast(
    data,
    variable,
    low,
    high,
    outcomes,
):
    if variable in {"p", "fn_rate"}:
        low_part = data[
            close_mask(
                data[variable],
                low,
            )
        ]

        high_part = data[
            close_mask(
                data[variable],
                high,
            )
        ]

    else:
        low_part = data[
            data[variable] == low
        ]

        high_part = data[
            data[variable] == high
        ]

    low_df = (
        low_part
        .groupby(
            "scenario_id"
        )[outcomes]
        .mean()
    )

    high_df = (
        high_part
        .groupby(
            "scenario_id"
        )[outcomes]
        .mean()
    )

    result = (
        high_df
        - low_df
    )

    result.insert(
        0,
        "contrast",
        f"{variable}: {low} -> {high}",
    )

    return (
        result.reset_index()
    )


# ======================================================================
# LOAD AND VALIDATE
# ======================================================================

if not INPUT.exists():
    raise FileNotFoundError(
        "Combined simulation output not found:\n"
        f"{INPUT}\n\n"
        "Run institutional_containment_stress_test.py first."
    )


df = pd.read_csv(
    INPUT
)


if len(df) != 784:
    raise RuntimeError(
        f"Expected 784 rows; obtained {len(df)}."
    )


required_columns = {
    "scenario_id",
    "scenario_name",
    "directed_edges",
    "topology_density",
    "origin_out_degree",
    "p",
    "tau",
    "fn_rate",
    *OUTCOMES,
}

missing = (
    required_columns
    - set(df.columns)
)

if missing:
    raise RuntimeError(
        "Missing required columns:\n"
        f"{sorted(missing)}"
    )


observed_scenarios = set(
    df["scenario_id"].unique()
)

expected_scenarios = set(
    SCENARIO_ORDER
)

if (
    observed_scenarios
    != expected_scenarios
):
    raise RuntimeError(
        "Unexpected scenario IDs.\n\n"
        f"Expected: {sorted(expected_scenarios)}\n"
        f"Observed: {sorted(observed_scenarios)}"
    )


counts = (
    df.groupby(
        "scenario_id"
    )
    .size()
)


for scenario in SCENARIO_ORDER:

    count = int(
        counts.get(
            scenario,
            0,
        )
    )

    if count != 196:
        raise RuntimeError(
            f"{scenario}: expected 196 rows; "
            f"obtained {count}."
        )


# ======================================================================
# DERIVED OUTCOME
# ======================================================================

df[
    "bounded_leakage_gap_pp"
] = (
    df[
        "cross_cell_leakage_pct"
    ]
    - df[
        "systemic_contagion_pct"
    ]
)


if (
    df[
        "bounded_leakage_gap_pp"
    ]
    < -1e-10
).any():
    raise RuntimeError(
        "Negative bounded-leakage gap detected. "
        "Check leakage and systemic-contagion definitions."
    )


ANALYSIS_OUTCOMES = (
    OUTCOMES
    + [
        "bounded_leakage_gap_pp"
    ]
)


# ======================================================================
# DESIGN-WIDE SCENARIO MEANS
# ======================================================================

overall = (
    df.groupby(
        [
            "scenario_id",
            "scenario_name",
            "directed_edges",
            "topology_density",
            "origin_out_degree",
        ],
        as_index=False,
    )[ANALYSIS_OUTCOMES]
    .mean()
)


scenario_order_map = {
    scenario: index
    for index, scenario
    in enumerate(
        SCENARIO_ORDER
    )
}


overall[
    "_scenario_order"
] = (
    overall[
        "scenario_id"
    ]
    .map(
        scenario_order_map
    )
)


overall = (
    overall
    .sort_values(
        "_scenario_order"
    )
    .drop(
        columns=[
            "_scenario_order"
        ]
    )
)


overall.to_csv(
    OUTDIR
    / "scenario_means.csv",
    index=False,
)


# ======================================================================
# MARGINALS: TOPOLOGY ~ p / tau / FN
# ======================================================================

by_p = (
    df.groupby(
        [
            "scenario_id",
            "p",
        ],
        as_index=False,
    )[ANALYSIS_OUTCOMES]
    .mean()
)


by_tau = (
    df.groupby(
        [
            "scenario_id",
            "tau",
        ],
        as_index=False,
    )[ANALYSIS_OUTCOMES]
    .mean()
)


by_fn = (
    df.groupby(
        [
            "scenario_id",
            "fn_rate",
        ],
        as_index=False,
    )[ANALYSIS_OUTCOMES]
    .mean()
)


by_p.to_csv(
    OUTDIR
    / "topology_by_p.csv",
    index=False,
)


by_tau.to_csv(
    OUTDIR
    / "topology_by_tau.csv",
    index=False,
)


by_fn.to_csv(
    OUTDIR
    / "topology_by_fn.csv",
    index=False,
)


# ======================================================================
# MATCHED-CONDITION CONTRASTS AGAINST S0
# ======================================================================

keys = [
    "p",
    "tau",
    "fn_rate",
]


base = (
    df[
        df[
            "scenario_id"
        ]
        == "S0_maximal_connectivity"
    ][
        keys
        + ANALYSIS_OUTCOMES
    ]
    .copy()
)


base = base.rename(
    columns={
        outcome:
            f"S0_{outcome}"
        for outcome
        in ANALYSIS_OUTCOMES
    }
)


contrast_frames = []


for scenario in (
    SCENARIO_ORDER[1:]
):

    part = (
        df[
            df[
                "scenario_id"
            ]
            == scenario
        ][
            [
                "scenario_id"
            ]
            + keys
            + ANALYSIS_OUTCOMES
        ]
        .copy()
    )


    merged = (
        part.merge(
            base,
            on=keys,
            how="left",
            validate="one_to_one",
        )
    )


    for outcome in (
        ANALYSIS_OUTCOMES
    ):

        merged[
            f"delta_{outcome}"
        ] = (
            merged[outcome]
            - merged[
                f"S0_{outcome}"
            ]
        )


    contrast_frames.append(
        merged
    )


contrasts = (
    pd.concat(
        contrast_frames,
        ignore_index=True,
    )
)


delta_columns = [
    f"delta_{outcome}"
    for outcome
    in ANALYSIS_OUTCOMES
]


overall_contrasts = (
    contrasts
    .groupby(
        "scenario_id",
        as_index=False,
    )[delta_columns]
    .mean()
)


contrast_by_p = (
    contrasts
    .groupby(
        [
            "scenario_id",
            "p",
        ],
        as_index=False,
    )[delta_columns]
    .mean()
)


contrast_by_tau = (
    contrasts
    .groupby(
        [
            "scenario_id",
            "tau",
        ],
        as_index=False,
    )[delta_columns]
    .mean()
)


contrast_by_fn = (
    contrasts
    .groupby(
        [
            "scenario_id",
            "fn_rate",
        ],
        as_index=False,
    )[delta_columns]
    .mean()
)


overall_contrasts.to_csv(
    OUTDIR
    / "contrasts_vs_S0.csv",
    index=False,
)


contrast_by_p.to_csv(
    OUTDIR
    / "contrasts_vs_S0_by_p.csv",
    index=False,
)


contrast_by_tau.to_csv(
    OUTDIR
    / "contrasts_vs_S0_by_tau.csv",
    index=False,
)


contrast_by_fn.to_csv(
    OUTDIR
    / "contrasts_vs_S0_by_fn.csv",
    index=False,
)


# ======================================================================
# STRUCTURAL CHECKS
# ======================================================================

s0 = (
    df[
        df[
            "scenario_id"
        ]
        == "S0_maximal_connectivity"
    ]
    .sort_values(
        keys
    )
    .reset_index(
        drop=True
    )
)


s2 = (
    df[
        df[
            "scenario_id"
        ]
        == "S2_hub_mediated"
    ]
    .sort_values(
        keys
    )
    .reset_index(
        drop=True
    )
)


leakage_identical = (
    np.array_equal(
        s0[
            "cross_cell_leakage_pct"
        ].to_numpy(),
        s2[
            "cross_cell_leakage_pct"
        ].to_numpy(),
    )
)


systemic_s2_le_s0 = (
    np.all(
        s2[
            "systemic_contagion_pct"
        ].to_numpy()
        <=
        s0[
            "systemic_contagion_pct"
        ].to_numpy()
    )
)


pe_s2_le_s0 = (
    np.all(
        s2[
            "propagated_exposure"
        ].to_numpy()
        <=
        s0[
            "propagated_exposure"
        ].to_numpy()
    )
)


velocity_s2_ge_s0 = (
    np.all(
        s2[
            "strategic_velocity_pct"
        ].to_numpy()
        >=
        s0[
            "strategic_velocity_pct"
        ].to_numpy()
    )
)


structural_checks = (
    pd.DataFrame(
        [
            {
                "check":
                    "S0-S2 leakage identical across all 196 matched conditions",
                "passed":
                    leakage_identical,
            },
            {
                "check":
                    "S2 systemic contagion <= S0 in all 196 matched conditions",
                "passed":
                    systemic_s2_le_s0,
            },
            {
                "check":
                    "S2 propagated exposure <= S0 in all 196 matched conditions",
                "passed":
                    pe_s2_le_s0,
            },
            {
                "check":
                    "S2 strategic velocity >= S0 in all 196 matched conditions",
                "passed":
                    velocity_s2_ge_s0,
            },
        ]
    )
)


structural_checks.to_csv(
    OUTDIR
    / "structural_checks.csv",
    index=False,
)


# ======================================================================
# ENDPOINT CONTRASTS
# ======================================================================

endpoint_p = (
    endpoint_contrast(
        df,
        "p",
        0.001,
        0.020,
        ANALYSIS_OUTCOMES,
    )
)


endpoint_tau = (
    endpoint_contrast(
        df,
        "tau",
        0,
        6,
        ANALYSIS_OUTCOMES,
    )
)


endpoint_fn = (
    endpoint_contrast(
        df,
        "fn_rate",
        0.00,
        0.30,
        ANALYSIS_OUTCOMES,
    )
)


endpoint_all = (
    pd.concat(
        [
            endpoint_p,
            endpoint_tau,
            endpoint_fn,
        ],
        ignore_index=True,
    )
)


endpoint_all.to_csv(
    OUTDIR
    / "endpoint_contrasts.csv",
    index=False,
)


# ======================================================================
# ANCHOR CONDITION
# ======================================================================

anchor = (
    df[
        close_mask(
            df["p"],
            0.010,
        )
        & (
            df["tau"]
            == 5
        )
        & close_mask(
            df[
                "fn_rate"
            ],
            0.20,
        )
    ]
    .copy()
)


if len(anchor) != 4:
    raise RuntimeError(
        "Expected one anchor row per topology."
    )


anchor.to_csv(
    OUTDIR
    / "anchor_condition.csv",
    index=False,
)


# ======================================================================
# CONSOLE REPORT
# ======================================================================

pd.set_option(
    "display.max_columns",
    None,
)

pd.set_option(
    "display.width",
    220,
)

pd.set_option(
    "display.float_format",
    lambda x: f"{x:.4f}",
)


print()
print("=" * 100)
print(
    "SCENARIO MEANS ACROSS ALL 196 CONDITIONS"
)
print("=" * 100)


print(
    overall[
        [
            "scenario_id",
            "directed_edges",
            "topology_density",
            "origin_out_degree",
            "systemic_contagion_pct",
            "cross_cell_leakage_pct",
            "strategic_velocity_pct",
            "propagated_exposure",
            "compromised_execution_persistence",
            "bounded_leakage_gap_pp",
        ]
    ]
    .to_string(
        index=False
    )
)


print()
print("=" * 100)
print(
    "MEAN CONTRASTS RELATIVE TO S0"
)
print("=" * 100)

print(
    overall_contrasts
    .to_string(
        index=False
    )
)


print()
print("=" * 100)
print(
    "STRUCTURAL CHECKS"
)
print("=" * 100)


for _, row in (
    structural_checks
    .iterrows()
):

    status = (
        "PASS"
        if row["passed"]
        else "FAIL"
    )

    print(
        f"[{status}] "
        f"{row['check']}"
    )


print()
print("=" * 100)
print(
    "LOW-TO-HIGH ENDPOINT CONTRASTS"
)
print("=" * 100)

print(
    endpoint_all
    .to_string(
        index=False
    )
)


print()
print("=" * 100)
print(
    "ANALYSIS COMPLETED"
)
print("=" * 100)

print(
    f"Input   : {INPUT}"
)

print(
    f"Outputs : {OUTDIR.resolve()}"
)
